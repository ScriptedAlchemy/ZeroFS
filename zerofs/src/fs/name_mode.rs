use serde::{Deserialize, Serialize};
use std::borrow::Cow;

use super::name_uppercase::SIMPLE_UPPERCASE;

#[cfg(test)]
#[path = "name_mode_vectors.rs"]
mod vectors;

/// The lookup rule is fixed when the filesystem is created.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum NameMode {
    #[default]
    Sensitive,
    Insensitive,
}

impl NameMode {
    pub fn key<'a>(self, name: &'a [u8]) -> Cow<'a, [u8]> {
        match self {
            Self::Sensitive => Cow::Borrowed(name),
            Self::Insensitive => fold_name(name),
        }
    }
}

/// How one request matches a client-supplied name against a stored entry.
///
/// `Folded` finds the entry whose folded key equals the name's. `Exact` also
/// requires the stored spelling to equal the name byte for byte. On a
/// sensitive filesystem the key is the stored spelling, so both agree.
/// Creation never uses this choice: fold-equal names always collide.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum NameMatch {
    #[default]
    Folded,
    Exact,
}

/// Apply OpenZFS Unicode 5.0.0 simple uppercase without normalization.
/// Invalid spans consume the lead byte's full width, including any ASCII tail.
/// Illegal lead bytes consume one byte. Truncated spans consume the remainder.
/// Inventory and filesystem lookup must use this same byte rule.
pub fn fold_name(name: &[u8]) -> Cow<'_, [u8]> {
    let mut folded = Vec::with_capacity(name.len());
    let mut rest = name;
    while let Some(&lead) = rest.first() {
        let width = match lead {
            0xc2..=0xdf => 2,
            0xe0..=0xef => 3,
            0xf0..=0xf4 => 4,
            _ => 1,
        };
        let (span, tail) = rest.split_at(width.min(rest.len()));
        match std::str::from_utf8(span) {
            Ok(valid) => fold_valid(valid, &mut folded),
            Err(_) => folded.extend_from_slice(span),
        }
        rest = tail;
    }
    if folded == name {
        Cow::Borrowed(name)
    } else {
        Cow::Owned(folded)
    }
}

fn fold_valid(valid: &str, output: &mut Vec<u8>) {
    for character in valid.chars() {
        let upper = if character.is_ascii() {
            character.to_ascii_uppercase()
        } else {
            SIMPLE_UPPERCASE
                .binary_search_by_key(&character, |&(from, _)| from)
                .map(|index| SIMPLE_UPPERCASE[index].1)
                .unwrap_or(character)
        };
        output.extend_from_slice(upper.encode_utf8(&mut [0; 4]).as_bytes());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn openzfs_byte_vectors() {
        for &(name, expected) in vectors::OPENZFS_VECTORS {
            assert_eq!(
                NameMode::Insensitive.key(name).as_ref(),
                expected,
                "{name:02x?}"
            );
        }
    }

    #[test]
    #[ignore = "requires the corpus generated by scripts/compare-openzfs-name-fold.py"]
    fn openzfs_offline_reference_corpus() {
        let path = std::env::var_os("ZEROFS_NAME_FOLD_REFERENCE").expect("reference corpus path");
        let corpus = std::fs::read(path).unwrap();
        let mut rest = corpus.as_slice();
        let mut counts = [0; 9];
        while !rest.is_empty() {
            let name_len = rest[0] as usize;
            let expected_len = rest[1] as usize;
            let name = &rest[2..2 + name_len];
            let expected = &rest[2 + name_len..2 + name_len + expected_len];
            assert_eq!(
                NameMode::Insensitive.key(name).as_ref(),
                expected,
                "{name:02x?}"
            );
            counts[name_len] += 1;
            rest = &rest[2 + name_len + expected_len..];
        }
        assert_eq!(counts[1], 256);
        assert_eq!(counts[2], 65_536);
        assert_eq!(counts[3..=8].iter().sum::<usize>(), 200_000);
        println!("OpenZFS reference comparisons passed: {counts:?}");
    }

    #[test]
    fn malformed_multibyte_sequence_keeps_its_ascii_tail() {
        assert_eq!(NameMode::Insensitive.key(b"\xc3a"), b"\xc3a".as_slice());
        assert_ne!(
            NameMode::Insensitive.key(b"\xc3a"),
            NameMode::Insensitive.key(b"\xc3A")
        );
    }

    #[test]
    fn unicode_5_simple_uppercase_examples() {
        for (name, expected) in [
            ("aAz", "AAZ"),
            ("éàø", "ÉÀØ"),
            ("ß", "ß"),
            ("ı", "I"),
            ("ſ", "S"),
            ("ςσ", "ΣΣ"),
            ("\u{a7d1}", "\u{a7d1}"),
            ("", ""),
        ] {
            assert_eq!(
                NameMode::Insensitive.key(name.as_bytes()),
                expected.as_bytes()
            );
            assert_eq!(NameMode::Sensitive.key(name.as_bytes()), name.as_bytes());
        }
        assert_ne!(
            NameMode::Insensitive.key("é".as_bytes()),
            NameMode::Insensitive.key("e\u{301}".as_bytes())
        );
    }

    #[test]
    fn invalid_utf8_passes_through_between_folded_letters() {
        assert_eq!(
            NameMode::Insensitive.key(b"a\xffb\xc3\xa9\xc0c\xe2\x82"),
            b"A\xffB\xc3\x89\xc0C\xe2\x82".as_slice()
        );
        assert_eq!(NameMode::Sensitive.key(b"a\xffb"), b"a\xffb".as_slice());
    }

    #[test]
    fn table_is_ordered_and_folding_is_idempotent() {
        assert!(
            SIMPLE_UPPERCASE
                .windows(2)
                .all(|pair| pair[0].0 < pair[1].0)
        );
        for &(lower, upper) in SIMPLE_UPPERCASE {
            let mut bytes = [0; 4];
            let key = NameMode::Insensitive.key(lower.encode_utf8(&mut bytes).as_bytes());
            assert_eq!(std::str::from_utf8(&key).unwrap(), upper.to_string());
            assert_eq!(NameMode::Insensitive.key(&key), key);
        }
    }
}
