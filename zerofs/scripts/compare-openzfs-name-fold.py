#!/usr/bin/env python3
"""Generate an offline reference from the OpenZFS 2.3.4 uppercase tables.

Read downloaded source as data. The byte-span rules emulate the simple-case
branch of u8_textprep_str with IGNORE_INVALID and IGNORE_NULL. IGNORE_NULL lets
the exhaustive corpus include NUL, which cannot occur in a filesystem name.
No OpenZFS code is executed.
"""

import argparse
import ast
import hashlib
import itertools
import json
from pathlib import Path
import random
import re


def table(source, name):
    match = re.search(r"\b" + name + r"((?:\[\d+\])+|)\s*=\s*(\{.*?\});", source, re.S)
    if match is None:
        raise ValueError(name)
    sizes = [int(size) for size in re.findall(r"\d+", match[1])]
    values = match[2].replace("{", "[").replace("}", "]")
    values = re.sub(r"\bN_\b", "255", values)
    values = re.sub(r"\bFIL_\b", "247", values)

    def pad(items, dimensions):
        if not dimensions:
            return items
        items = items + [0] * (dimensions[0] - len(items))
        if len(dimensions) == 1:
            return items
        return [pad(item if isinstance(item, list) else [], dimensions[1:]) for item in items]

    return pad(ast.literal_eval(values), sizes)


class Reference:
    def __init__(self, header):
        source = re.sub(r"/\*.*?\*/", "", header.read_text(), flags=re.S)
        self.b1 = table(source, "u8_common_b1_tbl")[1]
        self.b2 = table(source, "u8_case_common_b2_tbl")[1]
        self.b3 = table(source, "u8_toupper_b3_tbl")[1]
        self.b4 = table(source, "u8_toupper_b4_tbl")[1]
        self.final = table(source, "u8_toupper_final_tbl")[1]

    def convert(self, span):
        b1, b2, b3, b4 = bytes(4 - len(span)) + span
        b1 = self.b1[b1]
        if b1 == 255:
            return span
        b2 = self.b2[b1][b2]
        if b2 == 255:
            return span
        row, base = self.b3[b2][b3]
        if row == 255:
            return span
        start, end = self.b4[row][b4 : b4 + 2]
        if start >= end or end - start > 4:
            return span
        return bytes(self.final[base + start : base + end])

    def fold(self, name):
        output = bytearray()
        offset = 0
        while offset < len(name):
            lead = name[offset]
            if 0xC2 <= lead <= 0xDF:
                width = 2
            elif 0xE0 <= lead <= 0xEF:
                width = 3
            elif 0xF0 <= lead <= 0xF4:
                width = 4
            else:
                width = 1
            span = name[offset : offset + width]
            if width == 1:
                output.extend(bytes([lead - 32 if 97 <= lead <= 122 else lead]))
            elif len(span) < width:
                output.extend(span)
            else:
                output.extend(self.convert(span))
            offset += width
        return bytes(output)


def corpus(seed):
    for length in [1, 2]:
        for values in itertools.product(range(256), repeat=length):
            yield bytes(values)
    rng = random.Random(seed)
    fragments = [b"a", b"Z", b"\xc3\xa9", b"\xc3a", b"\xc3A", b"\xe2\x82", b"\xed\xa0\x80", b"\xf0\x90\x90\xa8", b"\xf4\x90aa", b"\xff", b"\x80", b"\xc0a", b"\xe0aa", b"\xf5a"]
    for index in range(200_000):
        length = 3 + index % 6
        if index % 2:
            yield bytes(rng.randrange(256) for _ in range(length))
        else:
            mixed = b""
            while len(mixed) < length:
                mixed += rng.choice(fragments)
            yield mixed[:length]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_dir", type=Path)
    parser.add_argument("corpus", type=Path)
    parser.add_argument("vectors", type=Path)
    args = parser.parse_args()
    reference = Reference(args.source_dir / "u8_textprep_data.h")
    count = 0
    digest = hashlib.sha256()
    with args.corpus.open("wb") as output:
        for name in corpus(0x5A465332):
            expected = reference.fold(name)
            record = bytes([len(name), len(expected)]) + name + expected
            digest.update(record)
            output.write(record)
            count += 1
    names = [b"\xc3a", b"\xc3A", b"a\xffb", b"\xc0a", b"\xc1a", b"\xe0ab", b"\xed\xa0a", b"\xf0abc", b"\xf4\x90ab", b"\xf5abc", b"\xc3", b"\xe2a", b"\xe2\x82", b"\xf0ab", b"a\xe2b", b"a\xc3ab", b"\xe2\xc3\xa9a", b"\xf0\xc3\xa9a", b"\xff\xc3\xa9", b"\x80a", b"\xbfz", b"\xfea", b"\xffa", "éςıſß".encode(), "\U00010428".encode()]
    args.vectors.write_text(
        "// Generated by scripts/compare-openzfs-name-fold.py from OpenZFS 2.3.4 data.\n"
        "pub(super) const OPENZFS_VECTORS: &[(&[u8], &[u8])] = &[\n"
        + "".join("    (&[" + ", ".join(f"0x{byte:02x}" for byte in name) + "], &[" + ", ".join(f"0x{byte:02x}" for byte in reference.fold(name)) + "]),\n" for name in names)
        + "];\n"
    )
    print(json.dumps({"records": count, "seed": "0x5a465332", "corpus_sha256": digest.hexdigest(), "source_sha256": {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(args.source_dir.iterdir()) if path.suffix in {".c", ".h"}}}))


if __name__ == "__main__":
    main()
