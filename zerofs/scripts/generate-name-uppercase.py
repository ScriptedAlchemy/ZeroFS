#!/usr/bin/env python3
"""Generate the Unicode 5.0.0 simple uppercase table from UnicodeData.txt."""
import argparse
import hashlib
from pathlib import Path

SOURCE = "https://www.unicode.org/Public/5.0.0/ucd/UnicodeData.txt"


def generate(source: Path) -> str:
    data = source.read_bytes()
    pairs = []
    previous = -1
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        if len(fields) != 15:
            raise ValueError("UnicodeData rows must contain 15 fields")
        codepoint = int(fields[0], 16)
        if not previous < codepoint <= 0x10FFFF:
            raise ValueError("UnicodeData codepoints must be ordered and unique")
        previous = codepoint
        if fields[12]:
            upper = int(fields[12], 16)
            if not 0 <= upper <= 0x10FFFF or any(0xD800 <= c <= 0xDFFF for c in [codepoint, upper]):
                raise ValueError("Case mappings must contain Unicode scalar values")
            pairs.append((codepoint, upper))
    header = (
        "// This file was generated by scripts/generate-name-uppercase.py.\n"
        f"// The source is {SOURCE}.\n"
        f"// The source SHA-256 is {hashlib.sha256(data).hexdigest()}.\n"
        "// UnicodeData field 12 supplies Unicode 5.0.0 simple uppercase mappings.\n\n"
        "pub(super) const SIMPLE_UPPERCASE: &[(char, char)] = &[\n"
    )
    return header + "".join(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),\n" for a, b in pairs) + "];\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.source))
